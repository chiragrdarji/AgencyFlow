export interface MetaTags {
  title: string;
  description: string;
  keywords?: string;
  ogTitle?: string;
  ogDescription?: string;
  ogImage?: string;
  ogUrl?: string;
  twitterCard?: string;
  twitterTitle?: string;
  twitterDescription?: string;
  twitterImage?: string;
  canonical?: string;
}

export const getMetaTags = (pageKey: keyof typeof seoConfig.pages): MetaTags => {
  const page = seoConfig.pages[pageKey];
  
  return {
    title: page.title,
    description: page.description,
    keywords: page.keywords,
    ogTitle: page.title,
    ogDescription: page.description,
    ogImage: seoConfig.ogdefaultImage,
    ogUrl: `${seoConfig.baseUrl}${page.path}`,
    twitterCard: 'summary_large_image',
    twitterTitle: page.title,
    twitterDescription: page.description,
    twitterImage: seoConfig.defaultImage,
    canonical: `${seoConfig.baseUrl}${page.path}`,
  };
};
